"""Retrieval quality: vector vs BM25 vs hybrid, and calibration of the relevance gate.

Uses the labelled queries in evaluation/retrieval_queries.json (no LLM needed, ~10 s).

- Hit@1 / Hit@k: a relevant document is the first result / among the top k chunks.
- MRR: mean of 1 / (rank of the first relevant chunk).
- Gate: "relevant" queries must keep at least one chunk; "negative" queries must keep none.

    python scripts/evaluate_retrieval.py
"""
from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.stdout.reconfigure(errors="replace")  # never crash on consoles that can't show — or ✗

from backend.retrieval.config import MIN_SCORE, TOP_K  # noqa: E402
from backend.retrieval.retriever import Retriever  # noqa: E402

QUERIES = ROOT / "evaluation" / "retrieval_queries.json"
OUT = ROOT / "evaluation" / "retrieval_eval.md"


def evaluate(retriever: Retriever, mode: str, relevant: list[dict]) -> dict:
    hits1 = hitsk = 0
    rr = []
    for item in relevant:
        ranked = retriever.rank(item["query"], mode)
        sources = [retriever.chunks[i].source for i, _ in ranked]
        first = next((r for r, s in enumerate(sources, 1) if s in item["docs"]), None)
        hits1 += first == 1
        hitsk += first is not None and first <= TOP_K
        rr.append(1 / first if first else 0.0)
    n = len(relevant)
    return {"hit1": hits1 / n, "hitk": hitsk / n, "mrr": sum(rr) / n}


def main() -> None:
    data = json.loads(QUERIES.read_text(encoding="utf-8"))
    relevant, negative = data["relevant"], data["negative"]

    retriever = Retriever()
    retriever.load()
    if not retriever.ready:
        sys.exit(f"Retriever not ready: {retriever.error}")

    rows = {mode: evaluate(retriever, mode, relevant) for mode in ("vector", "bm25", "hybrid")}

    # Relevance gate (uses cosine similarity, same for every mode)
    pos_best = [max(s for _, s in retriever.rank(q["query"], "vector")) for q in relevant]
    neg_best = [max(s for _, s in retriever.rank(q, "vector")) for q in negative]
    pos_pass = sum(s >= MIN_SCORE for s in pos_best)
    neg_reject = sum(s < MIN_SCORE for s in neg_best)

    lines = [
        "# Retrieval evaluation",
        "",
        f"{len(relevant)} labelled questions + {len(negative)} off-topic questions, "
        f"{len(retriever.chunks)} chunks, k = {TOP_K}. Generated by `scripts/evaluate_retrieval.py`.",
        "",
        f"| Method | Hit@1 | Hit@{TOP_K} | MRR |",
        "|---|---|---|---|",
    ]
    for mode, r in rows.items():
        lines.append(f"| {mode} | {r['hit1']:.0%} | {r['hitk']:.0%} | {r['mrr']:.3f} |")
    lines += [
        "",
        f"## Relevance gate (cosine >= {MIN_SCORE})",
        "",
        f"- Answerable questions kept: {pos_pass}/{len(relevant)} "
        f"(best-match cosine: min {min(pos_best):.2f}, median {statistics.median(pos_best):.2f})",
        f"- Off-topic questions rejected: {neg_reject}/{len(negative)} "
        f"(best-match cosine: max {max(neg_best):.2f}, median {statistics.median(neg_best):.2f})",
        "",
        "Off-topic best-match scores: " + ", ".join(f"{q!r}: {s:.2f}" for q, s in zip(negative, neg_best)),
        "",
        "Lowest answerable scores: "
        + ", ".join(f"{q['query']!r}: {s:.2f}" for q, s in sorted(zip(relevant, pos_best), key=lambda x: x[1])[:5]),
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
